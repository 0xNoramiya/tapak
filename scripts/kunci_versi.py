"""Write requirements.lock from the tested virtualenv: ``make kunci-versi``.

The Docker image installs exactly the versions in ``requirements.lock`` (``pip install --no-deps``,
then ``pip check``), so a rebuild gets the libraries the test suite ran against instead of the
latest release of every dependency. This script lists TAPAK's runtime dependencies (the
``[project].dependencies`` of pyproject.toml and everything they require, no extras such as
``dev``) with the version installed in the running interpreter, which must be the tested
``.venv`` (Python 3.12 on Linux, like the image).

    .venv/bin/python scripts/kunci_versi.py          # rewrite requirements.lock
    .venv/bin/python scripts/kunci_versi.py --cek    # exit 1 if it differs from this venv

Reads installed package metadata only; no network.
"""

from __future__ import annotations

import argparse
import difflib
import sys
import tomllib
from importlib.metadata import PackageNotFoundError, distribution
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "requirements.lock"
PYTHON = (3, 12)  # the image's Python (Dockerfile: python:3.12-slim-trixie)
HEADER = """\
# Runtime dependencies of TAPAK pinned to the versions of the tested virtualenv. The Docker image
# installs exactly these (Dockerfile: pip install --no-deps, then pip check).
# Generated by scripts/kunci_versi.py from {python} on {platform}; do not edit by hand.
# Refresh after changing the venv and running the tests: make kunci-versi (docs/operasi.md, Docker).
"""


def runtime_requirements(pyproject: Path = ROOT / "pyproject.toml") -> list[Requirement]:
    """``[project].dependencies`` of pyproject.toml (no optional extras)."""
    data = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    return [Requirement(r) for r in data["project"]["dependencies"]]


def _applies(req: Requirement, extras: frozenset[str]) -> bool:
    if req.marker is None:
        return True
    return any(req.marker.evaluate({"extra": e}) for e in extras | {""})


def closure(roots: list[Requirement]) -> dict[str, tuple[str, str, set[str]]]:
    """Every installed distribution the roots need: canonical name -> (name, version, required by).

    Raises SystemExit (Indonesian) when a requirement is not installed or the installed version
    does not satisfy it: the venv is not a tested, consistent environment then.
    """
    found: dict[str, tuple[str, str, set[str]]] = {}
    done: set[tuple[str, frozenset[str]]] = set()
    stack = [(req, "pyproject.toml") for req in roots if _applies(req, frozenset())]
    problems = []
    while stack:
        req, parent = stack.pop()
        key, extras = canonicalize_name(req.name), frozenset(req.extras)
        try:
            dist = distribution(req.name)
        except PackageNotFoundError:
            problems.append(f"{req} (dibutuhkan {parent}) tidak terpasang")
            continue
        if req.specifier and not req.specifier.contains(dist.version, prereleases=True):
            problems.append(f"{dist.metadata['Name']} {dist.version} tidak memenuhi {req} (dibutuhkan {parent})")
        found.setdefault(key, (dist.metadata["Name"], dist.version, set()))[2].add(parent)
        if (key, extras) in done:
            continue
        done.add((key, extras))
        for text in dist.requires or []:
            sub = Requirement(text)
            if _applies(sub, extras):
                stack.append((sub, key))
    if problems:
        raise SystemExit("virtualenv ini tidak konsisten dengan pyproject.toml:\n  " + "\n  ".join(problems))
    return found


def render(found: dict[str, tuple[str, str, set[str]]]) -> str:
    """The lock file text: one ``name==version`` per line, sorted, with what requires it."""
    impl = sys.implementation.name
    lines = [HEADER.format(python=f"{impl} {sys.version.split()[0]}", platform=sys.platform)]
    for key in sorted(found):
        name, version, via = found[key]
        lines.append(f"{key}=={version}\n    # via {', '.join(sorted(v for v in via))}\n")
    return "".join(lines)


def pins(text: str) -> dict[str, str]:
    """``name -> version`` of a lock file text (comments and blank lines ignored)."""
    out = {}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            name, _, version = line.partition("==")
            out[canonicalize_name(name)] = version.strip()
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Tulis requirements.lock dari virtualenv yang diuji")
    ap.add_argument("--cek", action="store_true", help="hanya bandingkan; kode keluar 1 bila berbeda")
    ap.add_argument("--lock", default=str(LOCK), help="berkas kunci (bawaan requirements.lock)")
    args = ap.parse_args(argv)
    if sys.version_info[:2] != PYTHON or not sys.platform.startswith("linux"):
        raise SystemExit(f"jalankan dengan Python {PYTHON[0]}.{PYTHON[1]} di Linux, sama dengan image "
                         f"(sekarang {sys.version.split()[0]} di {sys.platform})")
    found = closure(runtime_requirements())
    text = render(found)
    lock = Path(args.lock)
    if args.cek:
        old = lock.read_text(encoding="utf-8") if lock.is_file() else ""
        if pins(old) == pins(text):
            print(f"{lock.name} sama dengan virtualenv ini ({len(found)} pustaka)")
            return 0
        diff = difflib.unified_diff(
            [f"{k}=={v}\n" for k, v in sorted(pins(old).items())],
            [f"{k}=={v}\n" for k, v in sorted(pins(text).items())], lock.name, "virtualenv ini")
        sys.stdout.writelines(diff)
        print(f"{lock.name} berbeda dari virtualenv ini; jalankan make kunci-versi setelah pengujian lulus")
        return 1
    lock.write_text(text, encoding="utf-8")
    print(f"{lock.name}: {len(found)} pustaka dari {sys.prefix}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
